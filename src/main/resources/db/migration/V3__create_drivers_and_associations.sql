CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    license_number VARCHAR(60) NOT NULL,
    phone VARCHAR(40) NOT NULL,
    email VARCHAR(120),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    license_expiry_date DATE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_drivers_license_number UNIQUE (license_number),
    CONSTRAINT chk_drivers_status CHECK (status IN ('AVAILABLE', 'ASSIGNED', 'ON_LEAVE', 'INACTIVE'))
);

ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS assigned_driver_id BIGINT REFERENCES drivers(id) ON DELETE SET NULL;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP;

